#!/usr/bin/env bash
# gen-evaluator-cronjobs.sh — render one measure-evaluator CronJob per tenant.
#
# Reads the authoritative tenant roster from terraform/envs/<env>/secrets.enc.json
# (SOPS) and expands scripts/assets/measure-evaluator-cronjob.yaml once per tenant
# into components/measure-evaluator/overlays/<env>/cronjobs-generated.yaml.
#
# Why per-tenant CronJobs instead of one job looping the roster:
#   - each tenant gets its own activeDeadlineSeconds, so a slow tenant is bounded
#     on its own rather than eating a single whole-roster budget;
#   - schedules are staggered, so HAPI sees roughly one run at a time without
#     needing a parallelism dial — cheap now that a run is bulk searches rather
#     than $evaluate-measure, but still worth not firing the roster at once;
#   - one tenant failing leaves the others untouched, with their own job history.
#
# The roster here (SOPS) decides which CronJobs exist; the evaluator itself
# resolves the tenant from the backend's TenantRegistry (GCS), which is
# authoritative. A tenant onboarded without regenerating simply has no CronJob,
# and one removed leaves a CronJob whose ONLY_TENANT the registry rejects with a
# clear error — so drift surfaces rather than silently mis-reporting.
#
# IISc staging is not in this roster. Its CronJob is
# overlays/staging/cronjob-iisc-staging.yaml (external FHIR_BASE_URL).
#
# Usage:
#   scripts/gen-evaluator-cronjobs.sh --env staging
#   scripts/gen-evaluator-cronjobs.sh --env production --stagger 45
#
# Options:
#   --stagger <min>   minutes between tenant start times (default 30)
#   --start-hour <h>  hour of the first tenant's run (default 2)
#   --deadline <sec>  per-tenant activeDeadlineSeconds (default 900). A hang
#                     detector, not a performance budget — a run is ~3s.
#   --suspend         emit the CronJobs suspended, for a staged rollout: every
#                     Application syncs both envs with selfHeal, so the brake has
#                     to live in the manifest, not in a live kubectl patch

set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

STAGGER=30
START_HOUR=2
DEADLINE=900
SUSPEND=false
# The generated CronJobs carry per-tenant names, so env-specific values cannot be
# applied by a strategic-merge overlay patch: such a patch carries metadata.name
# and would rename every matched CronJob to the same thing. They are substituted
# here instead.
#
# These mirror the two per-env values that live inline in the fhir-gateway
# Deployment's overlay patch. The evaluator boots the backend's CoreModule, so
# Joi validates the same config schema and both must be present.
env_server_name() {
  case "$1" in
    staging)    echo "multi_tenant_staging" ;;
    production) echo "multi_tenant_production" ;;
  esac
}
env_secrets_id() {
  case "$1" in
    staging)    echo "aa-stg-arogyam-tenant-credentials" ;;
    production) echo "aa-prod-arogyam-tenant-credentials" ;;
  esac
}

EXTRA_ARGS=()
while [ "$#" -gt 0 ]; do
  case "$1" in
    --stagger)    STAGGER="$2"; shift 2 ;;
    --start-hour) START_HOUR="$2"; shift 2 ;;
    --deadline)     DEADLINE="$2"; shift 2 ;;
    --suspend)      SUSPEND=true; shift ;;
    *)            EXTRA_ARGS+=("$1"); shift ;;
  esac
done
parse_common_args "${EXTRA_ARGS[@]}"
require_cmd jq sops

[ -n "$ENV" ] || { log_err "--env {staging|production} is required"; exit 2; }
validate_env "$ENV"

SERVER_NAME=$(env_server_name "$ENV")
SECRETS_ID=$(env_secrets_id "$ENV")
[ -n "$SERVER_NAME" ] && [ -n "$SECRETS_ID" ] || { log_err "no per-env values for '$ENV'"; exit 2; }

TEMPLATE="$SCRIPT_DIR/assets/measure-evaluator-cronjob.yaml"
ENC="$REPO_ROOT/terraform/envs/$ENV/secrets.enc.json"
OUT="$REPO_ROOT/components/measure-evaluator/overlays/$ENV/cronjobs-generated.yaml"
[ -f "$TEMPLATE" ] || { log_err "no template at $TEMPLATE"; exit 1; }
[ -f "$ENC" ]      || { log_err "no $ENC"; exit 1; }

# Sorted, so the generated file is stable and index→schedule does not shuffle
# between runs. The evaluator sorts the same way.
# Not mapfile: bash 3.2 (macOS default) has no such builtin. Same read-loop
# read-loop idiom used elsewhere in scripts/.
TENANTS=()
while IFS= read -r t; do [ -n "$t" ] && TENANTS+=("$t"); done \
  < <(sops -d "$ENC" | jq -r '.tenants[]?' | sort)
[ "${#TENANTS[@]}" -gt 0 ] || { log_err "no .tenants[] in $ENC"; exit 1; }

count=${#TENANTS[@]}
work=$(mktemp)
trap 'rm -f "$work"' EXIT

{
  echo "# GENERATED by scripts/gen-evaluator-cronjobs.sh --env $ENV — do not edit."
  echo "# Source of truth: terraform/envs/$ENV/secrets.enc.json (.tenants[]) and"
  echo "# scripts/assets/measure-evaluator-cronjob.yaml. Regenerate after onboarding."
  echo "# ${count} tenants, ${STAGGER}min apart from ${START_HOUR}:00, ${DEADLINE}s each."
  echo "# suspended: ${SUSPEND}"
  echo "# server_name: ${SERVER_NAME}"
} >"$work"

i=0
for tenant in "${TENANTS[@]}"; do
  offset=$(( START_HOUR * 60 + i * STAGGER ))
  hour=$(( (offset / 60) % 24 ))
  minute=$(( offset % 60 ))
  schedule="$minute $hour * * *"
  {
    echo "---"
    sed -e "s/__TENANT__/${tenant}/g" \
        -e "s/__SCHEDULE__/${schedule}/g" \
        -e "s/__DEADLINE__/${DEADLINE}/g" \
        -e "s/__SERVER_NAME__/${SERVER_NAME}/g" \
        -e "s/__SECRETS_ID__/${SECRETS_ID}/g" \
        -e "s/__SUSPEND__/${SUSPEND}/g" \
        "$TEMPLATE" | grep -v '^# '
  } >>"$work"
  log_info "  ${tenant}: schedule='${schedule}'"
  i=$(( i + 1 ))
done

if cmp -s "$work" "$OUT" 2>/dev/null; then
  log_info "cronjobs-generated.yaml already up to date (${count} tenants)"
  exit 0
fi
cp "$work" "$OUT"
log_info "wrote $OUT (${count} tenants)"
log_info "commit it — ArgoCD applies these; bump the image tag in the overlay to deploy new evaluator code"
